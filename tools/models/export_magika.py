"""Reproduce the fixed Magika v3.3 CPU bundle. Development tool; not used by CMake.

Requires Python numpy + onnx. No inference runtime or Rust is needed to build/run HLS.
The model and metadata are Copyright Google LLC, Apache-2.0; see third_party/magika.
"""
import hashlib
import json
import pathlib
import struct

import numpy as np
import onnx
from onnx import numpy_helper

ROOT = pathlib.Path(__file__).resolve().parents[2]
VENDOR = ROOT / "third_party/magika"
SOURCE_SHA = "fe2d2eb49c5f88a9e0a6c048e15d6ffdf86235519c2afc535044de433169ec8c"


def export():
    source = VENDOR / "standard_v3_3.onnx"
    assert hashlib.sha256(source.read_bytes()).hexdigest() == SOURCE_SHA
    model = onnx.load(str(source))
    tensors = {t.name: numpy_helper.to_array(t) for t in model.graph.initializer}
    assert len(model.graph.input) == 1 and len(model.graph.output) == 1
    assert model.graph.input[0].type.tensor_type.shape.dim[1].dim_value == 2048
    assert model.graph.output[0].type.tensor_type.shape.dim[1].dim_value == 214
    prefix = "jax2tf_get_logits_/pjit_get_logits_/MagikaV2/"
    names = [
        ("embedding", "jax2tf_get_logits_/Const:0", (257, 64)),
        ("embedding_bias", prefix + "Dense_0/Reshape:0", (1, 1, 64)),
        ("norm0_scale", prefix + "LayerNorm_0/Reshape_2:0", (1, 512, 1)),
        ("norm0_bias", prefix + "LayerNorm_0/Reshape_3:0", (1, 512, 1)),
        ("convolution", prefix + "Conv_0/transpose_3:0", (512, 256, 5, 1)),
        ("convolution_bias", "const_fold_opt__209", (1, 512, 1)),
        ("norm1_scale", prefix + "LayerNorm_1/Reshape_2:0", (1, 512)),
        ("norm1_bias", prefix + "LayerNorm_1/Reshape_3:0", (1, 512)),
        ("classifier", "jax2tf_get_logits_/Const_24:0", (512, 214)),
        ("classifier_bias", prefix + "Dense_1/Reshape:0", (1, 214)),
    ]
    body = bytearray()
    header = ["#pragma once", "// Generated from the pinned Google Magika model by tools/models/export_magika.py.",
              "#include <cstddef>", "namespace hls { namespace magika { namespace data {",
              "struct Slice {std::size_t offset,count;};"]
    for name, key, shape in names:
        array = tensors[key]
        assert array.shape == shape and array.dtype == np.float32 and np.isfinite(array).all()
        if name == "convolution":
            # ONNX OIHW -> flattened (height,input-channel) x output-channel.
            array = array[:, :, :, 0].transpose(2, 1, 0)
        offset = len(body) // 4
        header.append(f"inline constexpr Slice {name}{{{offset},{array.size}}};")
        body.extend(array.astype("<f4").tobytes(order="C"))
        body.extend(b"\0" * (-len(body) % 64))
    metadata = b"HLSMAG33" + struct.pack("<II", 1, len(body) // 4)
    blob = metadata.ljust(64, b"\0") + body
    (VENDOR / "standard_v3_3.hlsm").write_bytes(blob)
    header += [f"inline constexpr std::size_t float_count={len(body)//4};",
               f"inline constexpr std::size_t blob_size={len(blob)};",
               "extern const unsigned char weights[];", "} } }"]
    (ROOT / "src/magika_layout.hpp").write_text("\n".join(header) + "\n", encoding="utf-8")
    config = json.loads((VENDOR / "config.min.json").read_text())
    knowledge = json.loads((VENDOR / "content_types_kb.min.json").read_text())
    labels = ["#pragma once", "// Google Magika metadata, Apache-2.0; generated by tools/models/export_magika.py.",
              "namespace hls { namespace magika {", "struct Label {const char *name,*mime,*extension,*category,*description;float threshold;bool text;};",
              "inline constexpr Label labels[]={"]
    aliases = {"unknown": "binary", "executable": "binary"}
    allowed = {"binary", "text", "code", "image", "audio", "video", "archive", "document", "sheet", "slides", "database", "font", "web"}
    for raw in config["target_labels_space"]:
        name = config["overwrite_map"].get(raw, raw)
        row = knowledge[name]
        mime = row.get("mime_type") or "application/octet-stream"
        group = aliases.get(row.get("group"), row.get("group"))
        if name == "html": group = "web"
        if group not in allowed: group = "text" if row["is_text"] else "binary"
        ext = next((e for e in row.get("extensions", []) if e and "." not in e and "/" not in e), "")
        values = [name, mime, ext, group, row["description"]]
        quoted = ",".join(json.dumps(v, ensure_ascii=False) for v in values)
        threshold = config["thresholds"].get(raw, config["medium_confidence_threshold"])
        labels.append("{" + quoted + f",{threshold}f," + ("true" if row["is_text"] else "false") + "},")
    labels += ["};", "} }"]
    (ROOT / "src/magika_labels.hpp").write_text("\n".join(labels) + "\n", encoding="utf-8")
    digest = hashlib.sha256(blob).hexdigest()
    print("Packed bundle:", len(blob), "bytes; SHA-256:", digest)
    return digest


if __name__ == "__main__":
    export()
